def clean(vtt, slug=''):
    lines = []
    for ln in vtt.split('\n'):
        if '-->' in ln or ln.startswith(('WEBVTT', 'Kind', 'Language')) or not ln.strip():
            continue
        ln = re.sub(r'<[^>]+>', '', ln).strip()
        if lines and lines[-1] == ln:
            continue
        lines.append(ln)
    t = re.sub(r'\s+', ' ', ' '.join(lines)).strip()
    for a, b in FIX + EXTRA.get(slug, []):
        t = t.replace(a, b)
    out = [s.strip() for s in re.split(r'(?<=[.?!])\s+', t) if s.strip()]
    # 초창기 회차의 자동 자막에는 문장 부호가 아예 없다. 그때는 마침표로 끊을 수가
    # 없으니 자막 줄을 그대로 이어 붙여 한 줄 60자 안팎으로 끊는다. 줄 번호가 인용
    # 주소라 한 줄이 통째로 나오면 인용이 못 쓰게 된다.
    if len(out) < max(2, len(t) // 400):
        out = []
        buf = ''
        for ln in lines:
            for a, b in FIX + EXTRA.get(slug, []):
                ln = ln.replace(a, b)
            buf = (buf + ' ' + ln).strip()
            if len(buf) >= 60:
                out.append(buf)
                buf = ''
        if buf:
            out.append(buf)
    return out


