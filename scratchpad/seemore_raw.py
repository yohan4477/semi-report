def clean(vtt, slug=''):
    lines = []
    for ln in vtt.split('\n'):
        if '-->' in ln or ln.startswith(('WEBVTT', 'Kind', 'Language')) or not ln.strip():
            continue
        ln = re.sub(r'<[^>]+>', '', ln).strip()
        if lines and lines[-1] == ln:
            continue
        lines.append(ln)
    t = re.sub(r'\s+', ' ', ' '.join(lines)).strip()
    for a, b in FIX + EXTRA.get(slug, []):
        t = t.replace(a, b)
    return [s.strip() for s in re.split(r'(?<=[.?!])\s+', t) if s.strip()]


