def main():
    vtt, slug, vid, title, date = sys.argv[1:6]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, 'content', 'understanding', '채널 씨모어', 'raw', slug + '.md')
    if os.path.exists(out):
        raise SystemExit('이미 있다 — 전사는 한 번 만들면 안 고친다: %s' % out)
    ss = clean(io.open(vtt, encoding='utf-8').read(), slug)
    io.open(out, 'w', encoding='utf-8', newline='').write(
        HEAD % (vid, title, date) + '\n'.join(ss) + '\n')
    print('%s — 문장 %d줄 · 글자 %d' % (slug, len(ss), sum(len(s) for s in ss)))


