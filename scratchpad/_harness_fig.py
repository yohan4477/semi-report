# -*- coding: utf-8 -*-
"""보고서 하네스·스킬 층의 도해 넷. 색은 회색만(확정 규칙 S2).

값은 전부 원문에 있는 것만 그린다 — 캡션이 라벨과 줄 번호를 댄다.
좌표는 _row 와 아래 헬퍼가 계산하고 손으로 찍지 않는다(yohan-figure 규칙 2).

이 층에서 특히 조심한 것 — 견줌 판이 셋(도해 1)이고 다섯(도해 3)인데,
판마다 칸 수가 다르면 견주는 눈이 흐려진다. 그래서 판 크기와 줄 수를 같게 두고
안에 적힌 말만 다르게 뒀다. 도해 4의 좌우 자리는 이 글이 가른 것이라 캡션에 밝힌다.
"""
import _biz_fig as bf

_svg, _box, _a, _lt, _row = bf._svg, bf._box, bf._a, bf._lt, bf._row
W = 640
INK, INK3 = 'var(--ink)', 'var(--ink-3)'

_DEFS = ('<defs><marker id="fig-arrow" viewBox="0 0 10 10" refX="9" refY="5" '
         'markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
         '<path d="M0 0 L10 5 L0 10 z" fill="%s"/></marker></defs>' % INK3)


def _t(cx, y, s, cls='t-sm'):
    return '<text x="%d" y="%d" text-anchor="middle" class="%s">%s</text>' % (cx, y, cls, s)


# ── 도해 1. 같은 물음에 세 곳이 다르게 답했다 ────────────────────────
# 견줄 때는 같은 꼴(확정 규칙). 세 판이 같은 크기이고 줄도 같은 두 줄이다 —
# 위가 모델에 남긴 것, 아래가 하네스가 가져간 것. 값이 아니라 각 원문의 서술이다.
_WCOL = _row(3, 0, 0, 196, gap=16)
_WHERE = [
    ('마이크로소프트 에이스', ['좁은 계약 하나에', '답하기'],
     ['단계 넘기기 · 결과 검증', '다음 행동 정하기']),
    ('커서 워크트리', ['워크트리 안에', '머무르기'],
     ['서브에이전트 띄우기', '결과 판정']),
    ('오픈AI 코덱스', ['위험한 행동인지', '심사하기'],
     ['샌드박스 · 컨텍스트 상한', '도구 지연 로딩']),
]


def _wpanel(i):
    x = _WCOL[i][0]
    name, top, bot = _WHERE[i]
    return ''.join([
        _t(x + 98, 40, name, 't-lab'),
        _box(x, 54, 196, 62, ['모델에 남긴 것'] + top, INK3, 1.5),
        _a(x + 98, 116, x + 98, 134),
        _box(x, 134, 196, 62, ['하네스가 가져간 것'] + bot, INK, 2.0),
    ])


FIG_WHERE = _svg(W, 232, '판단을 어디까지 걷어낼지에 세 곳이 다르게 답했다',
                 _DEFS + ''.join([_wpanel(i) for i in range(3)])
                 + _t(W // 2, 220, '세 판이 같은 크기다 — 다른 것은 안에 적힌 말뿐이다', 't-sm'))


# ── 도해 2. 컨텍스트 창에 넣는 손과 빼는 손 ──────────────────────────
# 가운데가 창이고 좌우가 그 창을 다루는 장치다. 장치 이름과 상한은 원문에 있는 것만.
_CIN = [['MCP', '바깥 도구·자료를 끌어온다'],
        ['메모리 되부름', '필요할 때만 도로 부른다'],
        ['스킬 본문', '쓰겠다고 정한 뒤에 읽는다']]
_COUT = [['컨텍스트 편집', '쓸모없어진 도구 결과를 지운다'],
         ['도구 지연 로딩', '창에 안 넣고 검색으로만 찾는다'],
         ['스킬 목록 2% 상한', '넘치면 설명을 줄인다']]
_CSTEP = 58
_CY0 = 46


def _ccol(x, cells):
    out = []
    for i, lines in enumerate(cells):
        out.append(_box(x, _CY0 + i * _CSTEP, 216, 46, lines, INK3, 1.5))
    return ''.join(out)


_CMID = (W - 152) // 2
FIG_CTX = _svg(W, 268, '컨텍스트 창에 넣는 손 셋과 빼는 손 셋', _DEFS + ''.join([
    _lt(8, 28, '넣는 손', 't-lab', True),
    _lt(W - 66, 28, '빼는 손', 't-lab', True),
    _ccol(0, _CIN),
    _ccol(W - 216, _COUT),
    _box(_CMID, _CY0 + _CSTEP, 152, 46, ['컨텍스트 창'], INK, 2.2),
    _a(216, _CY0 + _CSTEP + 23, _CMID, _CY0 + _CSTEP + 23),
    _a(_CMID + 152, _CY0 + _CSTEP + 23, W - 216, _CY0 + _CSTEP + 23),
]) + _t(W // 2, 254, '스킬 설명은 부를 때마다 백에서 이백 토큰이 늘 실린다', 't-sm'))


# ── 도해 3. 사고 다섯과 그때 없던 경계 다섯 ──────────────────────────
# 다섯 행이 전부 같은 꼴이다 — 왼쪽이 무엇이 났나, 오른쪽이 무엇이 없었나.
_FIVE = [('상태 구멍', '답장은 갔는데 그 턴이 어디에도 안 쓰였다', '상태 소유권'),
         ('겹친 기록자', '둘이 같은 옛 상태를 읽고 각자 저장했다', '커밋 시점의 질서'),
         ('매달린 툴 호출', '짝이 되는 결과가 오지 않는다', '마감 시한과 취소'),
         ('승인 표류', '만료된 승인이 재시작을 넘어 살아남았다', '행동에 묶인 권한'),
         ('놓친 엣지 증명', '성공을 보고했는데 화면에는 안 떴다', '사용자 경계의 확인')]
_FSTEP = 50
_FY0 = 44


def _frow(i):
    name, what, missing = _FIVE[i]
    y = _FY0 + i * _FSTEP
    return ''.join([
        _box(0, y, 172, 40, [name], INK, 1.8),
        _lt(184, y + 25, what, 't-sm', False),
        _box(W - 168, y, 168, 40, [missing], INK3, 1.5),
    ])


FIG_CHAIN = _svg(W, _FY0 + 5 * _FSTEP + 34, '사고 다섯과 그때 없던 경계 다섯',
                 _DEFS + ''.join([_lt(0, 28, '무엇이 났나', 't-lab', True),
                                  _lt(W - 168, 28, '무엇이 없었나', 't-lab', True)]
                                 + [_frow(i) for i in range(5)])
                 + _t(W // 2, _FY0 + 5 * _FSTEP + 22,
                      '다섯 다 오픈클로 공개 이슈에서 뽑은 것이다', 't-sm'))


# ── 도해 4. 열세 달, 누가 어느 쪽으로 갔나 ───────────────────────────
# 세로가 시간이고 좌우가 방향이다. **어느 쪽에 놓을지는 이 글이 가른 것**이고
# 각 줄에 적힌 말은 그 원문의 서술이다 — 캡션이 그렇게 밝힌다.
_TL = [('2025-08', 0, '앤스로픽', '견해를 안 갖고 헐겁게 둔다'),
       ('2025-12', 1, '오픈AI', '하네스가 새 추상화 계층이 된다'),
       ('2026-04', 1, '클라우드플레어', '도구를 둘로 줄여 코드로 부른다'),
       ('2026-05', 0, '커서', '격리 코드를 지우고 부탁으로'),
       ('2026-07', 1, '마이크로소프트', '단계 넘기기를 모델에서 뺏는다'),
       ('2026-08', 1, '오픈AI', '샌드박스 위에 심사관을 얹는다')]
_TSTEP = 52
_TY0 = 56
_TXL, _TXR = 72, 336
_TW = 250


def _trow(i):
    when, side, who, what = _TL[i]
    y = _TY0 + i * _TSTEP
    x = _TXR if side else _TXL
    st, sw = (INK, 2.0) if side else (INK3, 1.5)
    return ''.join([
        _lt(0, y + 26, when, 't-sm', True),
        _box(x, y, _TW, 40, [who, what], st, sw),
    ])


FIG_TIME = _svg(W, _TY0 + 6 * _TSTEP + 34, '열세 달 동안 판단이 어느 쪽으로 옮겼나',
                _DEFS + ''.join([
                    _lt(_TXL + 40, 34, '모델에 맡기는 쪽', 't-lab', True),
                    _lt(_TXR + 40, 34, '하네스가 가져가는 쪽', 't-lab', True),
                    '<path d="M%d %d V%d" stroke="%s" stroke-width="1" '
                    'stroke-dasharray="4 4" fill="none"/>'
                    % (_TXR - 14, _TY0 - 12, _TY0 + 6 * _TSTEP - 8, INK3),
                ] + [_trow(i) for i in range(6)])
                + _t(W // 2, _TY0 + 6 * _TSTEP + 22,
                     '왼쪽 둘이 같은 회사가 아니다 — 앤스로픽과 커서다', 't-sm'))
