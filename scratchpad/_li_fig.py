"""링크드인 흐름 장의 도해 셋. 색은 회색만(확정 규칙 S2).

값은 전부 게시물에 있는 것만 그린다 — 옆에 붙인 게시물 식별자로 check_liflow 가 되짚는다.
좌표는 _row 와 아래 헬퍼가 계산하고 손으로 찍지 않는다(insight-figure 규칙 2).

**건수 곡선은 안 그린다.** 요지 평균 자수가 4월 42자에서 8월 304자로 일곱 배가 되어
월별 언급 건수가 주제 이동이 아니라 요약 길이를 그린다(2026-09-06). 그리면 없는 흐름을
그리게 된다.
"""
import _biz_fig as bf

_svg, _box, _a, _lt, _row = bf._svg, bf._box, bf._a, bf._lt, bf._row
W = 640
INK, INK3 = 'var(--ink)', 'var(--ink-3)'


def _t(cx, y, s, cls='t-sm'):
    return '<text x="%d" y="%d" text-anchor="middle" class="%s">%s</text>' % (cx, y, cls, s)


# `.flow` 는 marker-end:url(#fig-arrow) 를 부르는데 그 marker 정의는 저장소에서
# epoch 장에만 있다(2026-09-06). 없으면 브라우저가 선만 긋고 화살촉을 안 그려서
# 「인과는 화살표로」가 조용히 안 지켜진다. 그래서 도해마다 자기 것을 들고 간다
_DEFS = ('<defs><marker id="fig-arrow" viewBox="0 0 10 10" refX="9" refY="5" '
         'markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
         '<path d="M0 0 L10 5 L0 10 z" fill="%s"/></marker></defs>' % INK3)


# ── 도해 1. 값이 오른 자리 — 공급망을 끝에서 끝까지 ──────────────────
# 확정 규칙 「밸류체인은 끝까지」·「사슬은 한 크기」. 상자 여섯이 전부 같은 크기이고
# 다른 것은 아래 붙인 날과 값뿐이다. 소재에서 완제품까지 순서대로 놓았는데 날짜는
# 그 순서를 안 따른다 — 그 어긋남이 이 그림이 보여 주려는 것이다.
_SH = _row(6, 44, 82, 96, gap=12)
# 값 글자가 상자 폭(96px)을 넘으면 옆 상자로 흘러 겹친다 — 처음 그렸을 때 여섯 칸이
# 통째로 겹쳤다(2026-09-06). 확정 규칙 「라벨이 넓어 판을 넘치면 라벨을 줄인다」대로
# 여덟 글자 안으로 줄이고, 무엇의 값인지는 캡션이 말한다
_SHIFT_CELLS = [
    (['소재·부품', '06-30', '텅스텐 −50%']),
    (['장비', '07-30', '캐펙스 +15%']),
    (['메모리', '03-31', '수출 +137%']),
    (['파운드리', '08-22', '물량 +6%']),
    (['기판', '08-27', '12~14개월']),
    (['완제품', '08-29', 'ASP +27%']),
]
FIG_SHIFT = _svg(W, 150, '값이 오른 자리 — 소재에서 완제품까지', _DEFS + ''.join(
    [_lt(8, 30, '공급망 위쪽', 't-sm', True),
     _lt(W - 76, 30, '아래쪽', 't-sm', True)]
    + [_box(x, y, w, h, lines, INK3, 1.5)
       for (x, y, w, h), lines in zip(_SH, _SHIFT_CELLS)]
    + [_a(_SH[i - 1][0] + _SH[i - 1][2], 85, _SH[i][0], 85) for i in range(1, 6)]
    + [_t(W // 2, 144, '아래 줄은 값이 오른 것이 확인된 날과 그 값', 't-sm')]))


# ── 도해 2. 전력 — 값 신호에서 계통 차단까지 ─────────────────────────
# 확정 규칙 「인과는 화살표로」. 세로 사슬이고 상자 크기가 전부 같다.
# 한 줄로 적었더니 7·8월 글자가 상자를 좌우로 넘쳤고 상자 사이 화살표가 16px 라
# 안 보였다(2026-09-06). 두 줄로 나누고 칸 사이를 벌린다 — 인과는 화살표로 잇는다는
# 규칙이 화살표가 눈에 보일 때만 지켜진다
_STEPS = [
    ('2026-03', ['용량시장 값이 신규 발전소 본전선 아래']),
    ('2026-04', ['90기가와트 증설에 전기공 14만 명', '자격 갖춘 사람은 그 일부']),
    ('2026-05', ['ERCOT 2030년 전망 29.6 → 77.9기가와트', '실제 승인은 월 1기가와트']),
    ('2026-06', ['데이터센터 건설 유예 50건 초과']),
    ('2026-07', ['왕복엔진이 비상용에서 상시 발전으로', '2027·2028년 각 4기가와트 초과']),
    ('2026-08', ['뉴욕 행정명령 62호 · ERCOT 대기열 474기가와트', '신규 접속 승인 중단']),
    ('2026-09', ['포츠머스 8기가와트 — 습지 허가 2026년 말', '부지 정화 2031년까지']),
]
_PBW, _PBH, _PSTEP = 496, 54, 84
_PX = (W - _PBW) // 2 + 22


def _step(i, when, lines):
    y = 20 + i * _PSTEP
    st, sw = (INK, 2.0) if i == 5 else (INK3, 1.5)
    out = [_lt(10, y + _PBH // 2 + 4, when, 't-sm', True),
           _box(_PX, y, _PBW, _PBH, lines, st, sw)]
    if i:
        out.append(_a(_PX + _PBW // 2, y - (_PSTEP - _PBH) + 4, _PX + _PBW // 2, y))
    return ''.join(out)


FIG_POWER = _svg(W, 20 + 7 * _PSTEP - (_PSTEP - _PBH) + 10,
                 '전력 — 값 신호가 나온 뒤 계통이 문을 닫기까지',
                 _DEFS + ''.join(_step(i, w, l) for i, (w, l) in enumerate(_STEPS)))


# ── 도해 3. 걸리는 시간 — 물리와 소프트웨어 ──────────────────────────
# 확정 규칙 「값을 견줄 때는 나란한 세로 막대, 높이는 값에 비례, 범위는 위 끝」.
# 소프트웨어 막대가 거의 안 보이는 것이 이 그림이 말하려는 것이다.
_MAX, _H0, _BASE = 36.0, 196, 236
# 라벨을 열한 글자에서 잘라 두 줄로 만들었더니 막대 폭(78px)을 넘어 옆 막대 라벨과
# 겹쳤다(2026-09-06). 자동으로 자르지 않고 줄을 직접 나눈다
_BARS = [
    (('인듐인', '새 생산능력'), 36.0, '2~3년', True),
    (('적층세라믹', '커패시터 라인'), 24.0, '2년', False),
    (('기판', '리드타임'), 14.0, '12~14개월', True),
    (('서빙 비용', '2.5배 절감'), 2.3, '70일', False),
    (('처리량', '6배 이상'), 0.5, '2주', False),
]
_BW, _BG = 78, 32
_BX0 = (W - (5 * _BW + 4 * _BG)) // 2


def _bar(i, lab, months, txt, top):
    x = _BX0 + i * (_BW + _BG)
    h = max(3, int(_H0 * months / _MAX))
    y = _BASE - h
    fill = 'var(--sunk)' if i < 3 else 'none'
    return ''.join([
        '<rect x="%d" y="%d" width="%d" height="%d" rx="4" fill="%s" stroke="%s" '
        'stroke-width="1.5"/>' % (x, y, _BW, h, fill, INK if i >= 3 else INK3),
        _t(x + _BW // 2, y - 8, txt + ('△' if top else ''), 't-lab'),
        _t(x + _BW // 2, _BASE + 18, lab[0], 't-sm'),
        _t(x + _BW // 2, _BASE + 34, lab[1], 't-sm'),
    ])


FIG_CLOCK = _svg(W, 300, '물리적인 것을 늘리는 데 걸리는 시간과 소프트웨어가 걸린 시간',
                 ''.join([
                     '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="1"/>'
                     % (_BX0 - 16, _BASE, W - _BX0 + 16, _BASE, INK3),
                     _lt(_BX0 - 16, 18, '왼쪽 셋은 물리 · 오른쪽 둘은 소프트웨어', 't-sm', True),
                 ] + [_bar(i, *b) for i, b in enumerate(_BARS)]
                     + [_t(W // 2, 292, '△ 는 범위의 위 끝. 높이는 개월 수에 비례한다', 't-sm')]))
