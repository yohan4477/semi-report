MARK = '## 반론 · 충돌'
for f in sorted(os.listdir(D)):
    key = f[:8]
    if key not in CLASH:
        print('SKIP', f)
        continue
    p = os.path.join(D, f)
    t = io.open(p, encoding='utf-8').read()
    t = re.sub(r'\n## 반론 · 충돌\n.*?(?=\n## )', '\n', t, flags=re.S)  # 재실행 안전
    body = MARK + '\n\n> 이 글 하나만 읽고 결론 내리지 않도록, 같은 채널의 다른 글이나 SemiAnalysis 코퍼스와 어긋나는 지점을 붙여 둔다.\n\n'
    body += '\n'.join('- **[%s]** %s' % (w, s) for w, s in CLASH[key]) + '\n\n'
    if '\n## 유보 사항' in t:
        t = t.replace('\n## 유보 사항', '\n' + body + '## 유보 사항', 1)
    else:
        t = t.rstrip() + '\n\n' + body
    io.open(p, 'w', encoding='utf-8').write(t)
    print('OK  ', f)
