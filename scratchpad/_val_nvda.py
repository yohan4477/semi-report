def _eok(v):
    """10억 달러 값을 「N억 달러」 표기로. 본문이 쓰는 단위에 맞춘다."""
    return format(int(round(v * 10)), ',') + '억 달러'


def _sens_table():
    """감도표(R25). 할인율 × 영구성장률 격자를 주당 달러로 낸다."""
    grid = nc.dcf.sensitivity([r[3] for r in nc.path(nc.CASES['Base'])],
                              nc.SENS_R, nc.SENS_G, nc.NET_DEBT, nc.SHARES)
    h = ['<div class="yt-wrap"><table class="yt">',
         '<colgroup><col style="width:104px">',
         ''.join('<col style="width:74px">' for _ in nc.SENS_G), '</colgroup>',
         '<thead><tr><th>할인율 \\ 영구</th>',
         ''.join('<th>%.2f%%</th>' % (g * 100) for g in nc.SENS_G),
         '</tr></thead><tbody>']
    for r in nc.SENS_R:
        cls = ' class="hi"' if abs(r - nc.WACC) < 1e-9 else ''
        h.append('<tr%s><th scope="row">%.2f%%</th>%s</tr>'
                 % (cls, r * 100,
                    ''.join('<td>%.0f</td>' % grid[(r, g)] for g in nc.SENS_G)))
    h.append('</tbody></table></div>')
    return ''.join(h)


