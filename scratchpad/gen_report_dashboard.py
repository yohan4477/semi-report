# 도해는 「무엇이 오가나」를 보이고, 만화는 「어느 쪽이 바쁜가」를 보인다.
# 얼굴은 상자에 점 둘과 선 하나. 말풍선은 둥근 상자에 꼬리 하나.
def _face(cx, cy, mood='flat', col='var(--ink)'):
    """얼굴 하나. mood = flat(무표정) · busy(땀) · talk(입 벌림)."""
    out = ['<rect x="%d" y="%d" width="64" height="52" rx="12" fill="none" stroke="%s" '
           'stroke-width="2.2"/>' % (cx - 32, cy - 26, col),
           '<circle cx="%d" cy="%d" r="3.4" fill="%s"/>' % (cx - 12, cy - 6, col),
           '<circle cx="%d" cy="%d" r="3.4" fill="%s"/>' % (cx + 12, cy - 6, col)]
    if mood == 'talk':
        out.append('<ellipse cx="%d" cy="%d" rx="9" ry="6" fill="none" stroke="%s" '
                   'stroke-width="2.2"/>' % (cx, cy + 12, col))
    elif mood == 'busy':
        out.append('<path d="M%d %d Q%d %d %d %d" fill="none" stroke="%s" stroke-width="2.2" '
                   'stroke-linecap="round"/>' % (cx - 11, cy + 15, cx, cy + 6, cx + 11, cy + 15, col))
        # 땀 두 방울
        out.append('<path d="M%d %d q4 6 0 8 q-4 -2 0 -8z" fill="%s"/>' % (cx + 34, cy - 18, col))
        out.append('<path d="M%d %d q4 6 0 8 q-4 -2 0 -8z" fill="%s"/>' % (cx - 38, cy - 12, col))
    else:
        out.append('<path d="M%d %d L%d %d" fill="none" stroke="%s" stroke-width="2.2" '
                   'stroke-linecap="round"/>' % (cx - 10, cy + 12, cx + 10, cy + 12, col))
    return ''.join(out)


def _bubble(x, y, w, lines, col='var(--ink-3)'):
    """말풍선. lines 는 두 줄까지."""
    h = 26 + 16 * (len(lines) - 1)
    out = ['<rect x="%d" y="%d" width="%d" height="%d" rx="10" fill="var(--paper)" '
           'stroke="%s" stroke-width="1.8"/>' % (x, y, w, h, col),
           '<path d="M%d %d L%d %d L%d %d z" fill="var(--paper)" stroke="%s" '
           'stroke-width="1.8"/>' % (x + 18, y + h, x + 30, y + h, x + 22, y + h + 10, col)]
    for i, t in enumerate(lines):
        out.append(_t(x + w // 2, y + 18 + i * 16, t, 't-sm'))
    return ''.join(out)


