# 맨 위는 축 여섯을 한 칸에 하나씩 따로 보여 준다(축 여섯을 한 그림에 겹쳐 그리면 아무도 못 읽는다).
# 가운데는 손 그림 — 엄지 축 셋만 점으로 센다. 손가락 쪽 배분은 원문에 없어 점을 찍지 않는다.
# 아래는 눈금 하나에 6·12~13·15~20·22 를 얹은 자다.
def _hand_block(cx, cy, col='var(--ink)'):
    """축 하나를 설명할 때 쓰는 팔 끝 — 손목 마디에 붙은 네모 하나."""
    return ('<rect x="%d" y="%d" width="30" height="20" rx="5" fill="var(--paper)" '
            'stroke="%s" stroke-width="2.6"/>'
            '<path d="M%d %d L%d %d" fill="none" stroke="%s" stroke-width="3.4" '
            'stroke-linecap="round"/>'
            % (cx - 15, cy - 10, col, cx + 15, cy, cx + 27, cy, col))


def _dash(x1, y1, x2, y2):
    """축이 어디로 서 있는지 — 도는 축은 이 선을 중심으로 돈다."""
    return ('<path d="M%s %s L%s %s" fill="none" stroke="var(--ink-3)" stroke-width="1.6" '
            'stroke-dasharray="5 4"/>' % (x1, y1, x2, y2))


def _cell(i, label, inner, y=32, h=104, w=96, gap=7, x0=14):
    """칸 하나 — 그림 위, 이름 아래. 칸 여섯이 곧 자유도 여섯이다."""
    x = x0 + i * (w + gap)
    return _r(x, y, w, h, 'var(--ink-3)', 1.4) + inner(x + w // 2) + _t(x + w // 2, y + h - 12,
                                                                       label, 't-sm')


def _cells():
    cy = 70

    def move_lr(cx):     # 좌우로 곧게
        return (_hand_block(cx, cy) + _a(cx - 20, cy, cx - 40, cy)
                + _a(cx + 30, cy, cx + 42, cy))

    def move_ud(cx):     # 위아래로 곧게
        return _hand_block(cx, cy) + _a(cx, cy - 14, cx, cy - 34) + _a(cx, cy + 14, cx, cy + 34)

    def move_fb(cx):     # 앞뒤로 곧게(비스듬한 축으로 그린다)
        return (_hand_block(cx, cy) + _a(cx - 14, cy + 12, cx - 34, cy + 28)
                + _a(cx + 14, cy - 12, cx + 34, cy - 28))

    def turn_yaw(cx):    # 선 축을 중심으로 좌우로 돌기
        return (_dash(cx, cy - 34, cx, cy + 34) + _hand_block(cx, cy)
                + '<path class="flow" fill="none" d="M%d %d A 34 13 0 1 0 %d %d"/>'
                % (cx - 34, cy + 26, cx + 30, cy + 26))

    def turn_pitch(cx):  # 누운 축을 중심으로 위아래로 젖히기
        return (_dash(cx - 36, cy, cx + 36, cy) + _hand_block(cx, cy)
                + '<path class="flow" fill="none" d="M%d %d A 30 30 0 1 1 %d %d"/>'
                % (cx + 22, cy - 24, cx - 2, cy + 26))

    def turn_roll(cx):   # 앞으로 뻗은 축을 중심으로 비틀기
        return (_dash(cx - 34, cy + 24, cx + 34, cy - 24) + _hand_block(cx, cy)
                + '<path class="flow" fill="none" d="M%d %d A 24 24 0 1 1 %d %d"/>'
                % (cx - 22, cy - 14, cx + 20, cy - 16))

    items = [('좌우로', move_lr), ('위아래로', move_ud), ('앞뒤로', move_fb),
             ('좌우로 돌기', turn_yaw), ('젖히기', turn_pitch), ('비틀기', turn_roll)]
    return ''.join(_cell(i, lab, fn) for i, (lab, fn) in enumerate(items))


def _cap(x, y, w, h, col='var(--ink)', sw=2.6, rot=None):
    """끝이 둥근 마디 하나 — 손가락과 엄지를 같은 부품으로 그린다."""
    tr = '' if rot is None else ' transform="rotate(%s %s %s)"' % rot
    return ('<rect x="%s" y="%s" width="%s" height="%s" rx="%s" fill="var(--paper)" '
            'stroke="%s" stroke-width="%s"%s/>' % (x, y, w, h, w / 2.0, col, sw, tr))


def _hand(dx=0, dy=0, col='var(--ink)', acc='var(--accent)'):
    """사람 손 하나 — 손바닥·손가락 넷·엄지. 엄지에만 축 셋을 점으로 찍는다(원문 값)."""
    import math
    out = [
        _cap(452 + dx, 186 + dy, 46, 34, col, 2.4),
        '<rect x="%d" y="%d" width="76" height="70" rx="18" fill="var(--paper)" '
        'stroke="%s" stroke-width="2.8"/>' % (438 + dx, 126 + dy, col),
    ]
    for fx, top in ((440, 74), (458, 60), (476, 68), (494, 88)):
        out.append(_cap(fx + dx, top + dy, 15, 148 - top, col, 2.4))
    bx, by, ln = 440.0 + dx, 192.0 + dy, 58.0
    out.append(_cap(432.5 + dx, 134 + dy, 15, 58, col, 2.4, rot=(-35, 440 + dx, 192 + dy)))
    ang = math.radians(-35)
    tx, ty = bx + ln * math.sin(ang), by - ln * math.cos(ang)
    for t in (0.14, 0.5, 0.86):
        out.append('<circle cx="%.1f" cy="%.1f" r="4.6" fill="var(--paper)" stroke="%s" '
                   'stroke-width="2.6"/>' % (bx + (tx - bx) * t, by + (ty - by) * t, acc))
    out.append('<path d="M%d %d L%d %d" fill="none" stroke="var(--ink-3)" '
               'stroke-width="1.6" stroke-dasharray="5 4"/>'
               % (432 + dx, 143 + dy, 520 + dx, 143 + dy))
    return ''.join(out)


def _scale(x0, y, x1, vmax=22):
    """자유도 자 하나 — 값 v 는 x0..x1 위 한 자리로만 간다(높이를 쓰지 않는다)."""
    def px(v):
        return x0 + (x1 - x0) * float(v) / vmax
    out = ['<path d="M%d %d L%d %d" fill="none" stroke="var(--ink-3)" stroke-width="2"/>'
           % (x0, y, x1, y)]
    out.append('<rect x="%.1f" y="%d" width="%.1f" height="14" rx="4" fill="none" '
               'stroke="var(--accent)" stroke-width="2.2"/>'
               % (px(15), y - 7, px(20) - px(15)))
    out.append('<rect x="%.1f" y="%d" width="%.1f" height="14" rx="4" fill="none" '
               'stroke="var(--ink-3)" stroke-width="1.8" stroke-dasharray="4 3"/>'
               % (px(12), y - 7, px(13) - px(12)))
    for v in (6, 22):
        out.append('<path d="M%.1f %d L%.1f %d" fill="none" stroke="var(--ink)" '
                   'stroke-width="2.4"/>' % (px(v), y - 9, px(v), y + 9))
    return ''.join(out), px


