"""보고서 ⑨ 트럼프 층의 도해 셋. 색은 회색만(확정 규칙) — 강조는 짙은 테두리 하나.

값은 전부 메르 원문에 있는 것만 쓴다(insight-figure 규칙 1). 상자 개수도 값이다 —
FIG_SWAP 의 네 걸음과 FIG_DELAY 의 다섯 줄은 원문이 센 수다. 유예 다섯은 메르가
「이번이 세 번째 연기」라고 직접 센 것을 이어 받은 것이고, 조항 넷은 실제로 근거가
바뀐 걸음만 세었다(Plan B 다섯 장 중 안 쓴 셋은 안 그린다).

자리는 _row 와 _step 이 계산한다. 손으로 찍지 않는다(규칙 2).
"""
import _biz_fig as bf

_svg, _box, _a, _lt, _row = bf._svg, bf._box, bf._a, bf._lt, bf._row
W = 640
INK, INK3, ACC = 'var(--ink)', 'var(--ink-3)', 'var(--accent)'


def _dashbox(x, y, w, h, lines):
    """아직 안 쓴 카드는 점선으로. 실선으로 그리면 이미 발동된 것으로 읽힌다."""
    cx, out = x + w // 2, ['<rect x="%d" y="%d" width="%d" height="%d" rx="8" fill="none" '
                           'stroke="%s" stroke-width="1.5" stroke-dasharray="5 4"/>'
                           % (x, y, w, h, INK3)]
    top = y + (h - (len(lines) - 1) * 16) // 2 + 5
    for i, s in enumerate(lines):
        out.append(bf._t(cx, top + i * 16, s, 't-lab' if i == 0 else 't-sm'))
    return ''.join(out)


