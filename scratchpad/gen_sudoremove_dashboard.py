# 좌표를 손으로 적는 일이 잦아 상자·글씨를 함수로 뽑았다 — 글자가 상자 밖으로 나가는지는
# 브라우저에서 getBBox 로 잰다(눈으로만 보면 다크모드에서 놓친다).


def _r(x, y, w, h, st='var(--ink-3)', sw=1.5, extra=''):
    return ('<rect x="%d" y="%d" width="%d" height="%d" rx="8" fill="none" '
            'stroke="%s" stroke-width="%s"%s/>' % (x, y, w, h, st, sw, extra))


def _t(cx, y, s, cls='t-lab'):
    return '<text x="%d" y="%d" text-anchor="middle" class="%s">%s</text>' % (cx, y, cls, s)


def _lt(x, y, s, cls='t-sm', bold=True):
    return ('<text x="%d" y="%d" class="%s"%s>%s</text>'
            % (x, y, cls, ' style="font-weight:850"' if bold else '', s))


def _a(x1, y1, x2, y2, dash=False):
    return ('<path d="M%d %d L%d %d" class="flow"%s/>'
            % (x1, y1, x2, y2, ' style="stroke-dasharray:5 4"' if dash else ''))


def _box(x, y, w, h, lines, st='var(--ink-3)', sw=1.5):
    """상자 하나 + 가운데 정렬한 줄들. 첫 줄은 t-lab, 나머지는 t-sm."""
    cx, out = x + w // 2, [_r(x, y, w, h, st, sw)]
    n = len(lines)
    top = y + (h - (n - 1) * 16) // 2 + 5
    for i, s in enumerate(lines):
        out.append(_t(cx, top + i * 16, s, 't-lab' if i == 0 else 't-sm'))
    return ''.join(out)



# 로봇 팔을 그리는 부품. 관절 각도를 손으로 어림하면 팔이 컵에 안 닿는다 —
# 손끝이 갈 자리를 정하고 팔꿈치는 역기구학으로 푼다(insight-figure 규칙 2).
def _ik(bx, by, tx, ty, l1, l2):
    """어깨(bx,by)에서 손끝(tx,ty)까지 두 마디로 갈 때 팔꿈치 자리. 팔꿈치는 위로 꺾는다."""
    import math
    dx, dy = tx - bx, ty - by
    d = min(math.hypot(dx, dy), l1 + l2 - 0.01)
    a = (d * d + l1 * l1 - l2 * l2) / (2 * d)
    h = math.sqrt(max(l1 * l1 - a * a, 0))
    ux, uy = dx / d, dy / d
    mx, my = bx + ux * a, by + uy * a
    return mx + uy * h, my - ux * h          # 법선 방향으로 h 만큼 — 위로 꺾인 쪽


def _arm(bx, by, tx, ty, col='var(--ink)', l1=84, l2=84):
    """어깨에서 손끝까지 두 마디 팔 + 관절 점 + 집게."""
    import math
    ex, ey = _ik(bx, by, tx, ty, l1, l2)
    ang = math.atan2(ty - ey, tx - ex)
    px, py = -math.sin(ang) * 7, math.cos(ang) * 7      # 집게 벌어지는 쪽
    gx, gy = math.cos(ang) * 9, math.sin(ang) * 9       # 집게 길이
    return ''.join([
        '<path d="M%.1f %.1f L%.1f %.1f L%.1f %.1f" fill="none" stroke="%s" '
        'stroke-width="5" stroke-linecap="round" stroke-linejoin="round"/>'
        % (bx, by, ex, ey, tx, ty, col),
        '<circle cx="%.1f" cy="%.1f" r="4.5" fill="var(--paper)" stroke="%s" stroke-width="2.5"/>'
        % (bx, by, col),
        '<circle cx="%.1f" cy="%.1f" r="4" fill="var(--paper)" stroke="%s" stroke-width="2.5"/>'
        % (ex, ey, col),
        '<path d="M%.1f %.1f L%.1f %.1f" fill="none" stroke="%s" stroke-width="3" '
        'stroke-linecap="round"/>' % (tx + px, ty + py, tx + px + gx, ty + py + gy, col),
        '<path d="M%.1f %.1f L%.1f %.1f" fill="none" stroke="%s" stroke-width="3" '
        'stroke-linecap="round"/>' % (tx - px, ty - py, tx - px + gx, ty - py + gy, col),
    ])


def _cup(x, y, col='var(--ink-2)'):
    return ('<path d="M%d %d L%d %d L%d %d L%d %d Z" fill="none" stroke="%s" '
            'stroke-width="2.5" stroke-linejoin="round"/>'
            % (x, y, x + 4, y + 24, x + 22, y + 24, x + 26, y, col))


def _scene(ox, oy, w, h, hand, cup, ghost=None, col='var(--ink)', imagined=False):
    """책상 하나에 로봇 팔 하나. 좌표는 칸 왼쪽 위(ox,oy) 기준.

    점선은 쓰지 않는다. 모델이 그려 낸 장면은 칸 테두리를 강조색으로 둘러 말하고,
    칸 안의 선은 실제 장면과 똑같이 그린다 — 팔은 진한 색, 물건은 흐린 색이다."""
    fr = ('var(--ink-3)', 2.2) if imagined else ('var(--line)', 1.3)
    out = [_r(ox, oy, w, h, fr[0], fr[1])]
    ty = oy + h - 34
    out.append('<path d="M%d %d L%d %d" fill="none" stroke="var(--line)" stroke-width="2.5"/>'
               % (ox + 12, ty, ox + w - 12, ty))
    if ghost:
        out.append(_cup(ox + ghost[0], oy + ghost[1], 'var(--line)'))
    out.append(_cup(ox + cup[0], oy + cup[1], 'var(--ink-3)'))
    out.append(_arm(ox + 34, ty - 4, ox + hand[0], oy + hand[1], col))
    return ''.join(out)

def _svg(w, h, label, body):
    return ('<svg viewBox="0 0 %d %d" role="img" aria-label="%s">%s</svg>'
            % (w, h, label, body))


