def _eok(v):
    """10억 달러 단위 값을 억 달러 표기로."""
    return '{:,.0f}억 달러'.format(v * 10)


def _pct(v, s='%.1f%%'):
    return s % (v * 100)


def _row(t):
    return [r for r in pr.rows() if r['t'] == t][0]


def _adj(t, key):
    hit = [r for r in adj.rows(t) if r['key'] == key]
    return hit[0] if hit else None


