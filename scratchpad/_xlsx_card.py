def card_html(head=True):
    """카드 본문. head 는 다른 층과 꼴을 맞추려고 받는다."""
    h = []
    if head:
        h.append('<div class="rep-head"><span class="rn">부록</span>'
                 '<h2 id="rep-model-xlsx">받은 엑셀 — 시트 그대로 보기</h2></div>')
    h.append(NOTE)
    for key, sheet, r1, r2, c1, c2, title, note in BLOCKS:
        h.append('<h3>%s</h3>' % title)
        h.append(xv.sheet_html(key, sheet, r1, r2, c1, c2, note))
    h.append(xv.downloads())
    return ''.join(h)
