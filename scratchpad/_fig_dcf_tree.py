# -*- coding: utf-8 -*-
"""07-16 삼성전자 DCF 를 math tree 로 쪼갠 도해 셋. 판을 세우는 코드는 `_mathtree`.

규칙은 `docs/규칙 — 도해.md` §1 「math tree」와 §5.

값을 어디에 적나 — 사슬 둘(적정가·FCF)은 카드 표 「적정가는 이 사슬로 나온다」가
바로 아래 붙으므로 판에는 이름만 둔다. WACC 는 그런 표가 없어 상자 둘째 줄에
값을 적는다. 적는 값은 원문 L74~L80 표에 있는 것만이고, 자기자본 비중은 원문이
안 적어(부채 비중만 적는다) 비워 두고 번호로 캡션에 넘긴다.
"""
from _mathtree import _node, tree_svg


# ── ① 주당 적정가가 갈라지는 자리. 카드 표 ④~⑨ 를 그림으로 ────────────────
FIG_PER_SHARE = tree_svg(
    '주당 적정가는 어떤 항들로 갈라지나',
    [120, 132, 140, 146],
    _node(['주당 적정가'], '÷', [
        _node(['주주지분가치'], '+', [
            _node(['총 영업가치', 'EV'], '+', [
                _node(['명시적 기간', 'FCF 의 현재가치']),
                _node(['영구가치의', '현재가치']),
            ]),
            _node(['순현금']),
        ]),
        _node(['발행주식수']),
    ]),
    marks=[('명시적 기간', 1), ('영구가치의', 2), ('발행주식수', 3)])


# ── ② 해마다의 FCF. 카드 표 ①~③ 을 그림으로 ────────────────────────────
FIG_FCF = tree_svg(
    '해마다의 FCF 는 매출에서 어떻게 나오나',
    [96, 96, 104, 112, 96],
    _node(['해마다의', 'FCF'], '−', [
        _node(['영업현금'], '+', [
            _node(['NOPAT'], '×', [
                _node(['영업이익'], '×', [
                    _node(['매출']),
                    _node(['영업이익률']),
                ]),
                _node(['1 − 법인세율']),
            ]),
            _node(['D&A']),
        ]),
        _node(['CAPEX']),
        _node(['순운전자본', '증가분']),
    ]),
    marks=[('NOPAT', 1), ('D&A', 2)])


# ── ③ 할인율. 원문 L74~L80 표를 그림으로 ─────────────────────────────────
FIG_WACC = tree_svg(
    'WACC 10.34% 는 다섯 입력으로 갈라진다',
    [80, 96, 148, 88, 76],
    _node(['WACC', '10.34%'], '+', [
        _node(['자기자본 몫'], '×', [
            _node(['Ke', '10.69%'], '+', [
                _node(['Rf', '4.20%']),
                _node(['β × MRP'], '×', [
                    _node(['β', '1.18']),
                    _node(['MRP', '5.50%']),
                ]),
            ]),
            _node(['자기자본 비중']),
        ]),
        _node(['타인자본 몫'], '×', [
            _node(['Kd 세후', '2.80%']),
            _node(['부채 비중', '4.44%']),
        ]),
    ]),
    marks=[('자기자본 비중', 1), ('Kd 세후', 2)])


# ── ④ 역산 — 시총이 요구하는 성장률이 어느 칸으로 들어가나 ─────────────────
# 원문 L43~L44 의 두 식을 그림으로. 되짚는 미지수(r)는 NOPAT5 안에만 든다.
FIG_REVERSE = tree_svg(
    '되짚기에서 성장률이 들어가는 칸은 하나다',
    [84, 100, 92, 108, 120],
    _node(['추정 EV', '753,027억원'], '+', [
        _node(['명시적 5년', '139,307억원']),
        _node(['영구가치 몫', '613,720억원'], '÷', [
            _node(['영구가치', '944,188억원'], '÷', [
                _node(['NOPAT₅ ×', '(1 + g)'], '×', [
                    _node(['NOPAT₅', '59,868억원']),
                    _node(['1 + g', 'g 2.5%']),
                ]),
                _node(['WACC − g', '9.0% − 2.5%']),
            ]),
            _node(['(1+WACC)⁵', 'WACC 9.0%']),
        ]),
    ]),
    marks=[('NOPAT₅', 1)])


if __name__ == '__main__':
    import sys
    sys.path.insert(0, 'scratchpad')
    import check_fig
    for name, fig in [('per_share', FIG_PER_SHARE), ('fcf', FIG_FCF), ('wacc', FIG_WACC),
                      ('reverse', FIG_REVERSE)]:
        print(name, check_fig.hits(fig) or 'FAIL 0건')
