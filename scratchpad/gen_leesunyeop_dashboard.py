# 합류도를 읽는 순서보다 먼저 세운다. 주제 열셋이 따로 놀지 않는다는 것이 이 페이지의
# 전제라, 그 전제를 그림 한 장으로 먼저 보이고 그다음에 어디서부터 읽을지를 준다.
def merge_intro():
    return ('<figure class="uc-fig"><p class="fig-title">주제는 하나로 합류한다</p>'
            + MERGE_SVG
            + '<figcaption>바깥에서 오는 변수 셋이 <b>미국 10년물 금리</b>와 <b>수급·조달 조건</b>을 '
              '거쳐 결국 <b>반도체 실적과 주주환원</b> 하나로 모인다. 카드 열셋은 이 그림의 어느 칸에 '
              '서느냐로 갈린다 — 카드를 펴면 그 주제가 다섯 달 동안 흘러온 길이 맨 앞에 나온다.'
              '</figcaption></figure>')


# 이 페이지에서는 읽는 순서를 접어 둔다. 합류도가 이미 위에 서 있어서 안내가 둘이면
# 카드 타일이 화면 밖으로 밀린다. 눌러야 펴지게 open을 뗀다 — dc.course()는 어느
# 페이지에서나 펼친 채로 내주므로 여기서만 닫는다.
def folded_course():
    h = dc.course(CARDS, COURSE, COURSE_LEDE)
    tag = '<details class="intro" open>'
    assert h.startswith(tag), h[:60]
    return '<details class="intro">' + h[len(tag):]


