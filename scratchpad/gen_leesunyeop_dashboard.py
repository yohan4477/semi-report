def log_html():
    """화면에는 **위로 갈수록 최신**으로 낸다 — 새 날짜를 보러 오는 층이라 맨 위가 어제여야 한다.

    LOG 자체는 오래된 것부터 적어 둔다. 새 날짜는 맨 뒤에 붙이면 되고 뒤집는 것은 여기서만 한다 —
    데이터를 거꾸로 적어 두면 새 줄을 앞에 끼워야 해서 손이 자주 어긋난다."""
    n = sum(len(v) for _m, v in LOG)
    h = ['<p class="ins-lede">원문 <b>100편</b>을 날짜순으로 훑는 층입니다. 주제 카드가 '
         '「무엇을 말했나」라면 여기는 <b>언제 말했나</b>입니다. <b>위로 갈수록 최신</b>이라 '
         '맨 위가 마지막 날이고, 아래로 내려갈수록 5월로 거슬러 올라갑니다. '
         '표시가 붙은 줄만 따로 읽으면 이 사람의 판단이 어디서 맞고 어디서 틀렸는지가 '
         '드러납니다 — 아래쪽 <b>예고</b>가 위쪽 <b>적중·빗나감</b>으로 받아집니다. '
         '나머지 날은 표시를 달지 않았습니다.</p>',
         '<div class="tlog">']
    for month, rows in reversed(LOG):
        rows = list(reversed(rows))
        h.append('<p class="tlog-m">%s · %d일</p><ul>' % (month, len(rows)))
        for d, tag, t in rows:
            h.append('<li%s><span class="d">%s</span>%s%s</li>'
                     % (' class="k"' if tag else '', d,
                        '<span class="tag t-%s">%s</span>' % (tag, tag) if tag else '', t))
        h.append('</ul>')
    h.append('</div>')
    return ''.join(h), n


