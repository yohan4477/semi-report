def _check_sections():
    """이 파일 맨 위의 SEC_* 가 생성기의 것과 한 글자도 안 다른지 본다. 생성기를 import 하지 않고 ast 로 읽는다."""
    import ast
    src = open(os.path.join(_ROOT, 'scratchpad', 'gen_accountant_dashboard.py'), encoding='utf-8-sig').read()
    want = {'SEC_SS', 'SEC_HY', 'SEC_APR', 'SEC_RATES', 'SEC_AI', 'SEC_MKT'}
    got = {}
    for n in ast.parse(src).body:
        if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', None) in want:
            got[n.targets[0].id] = ast.literal_eval(n.value)
    for k in want:
        assert got[k] == globals()[k], '섹션이 생성기와 다르다: ' + k


