def _sum(code):
    """요약 md 파일명을 날짜 머리말로 찾아 blob 주소를 낸다(파일명을 손으로 옮기다 틀리는 것을 막는다)."""
    hit = glob.glob(os.path.join(dc.ROOT, SUM, '[[]%s[]]*.md' % code))
    if len(hit) != 1:
        raise FileNotFoundError('요약 md 를 못 찾았다: %s %s' % (code, hit))
    return blob(SUM + os.path.basename(hit[0]))


