BY_ID = dict((a['id'], a) for a in AXES)


def cells(axis_id):
    """(칸 id, 이름, 설명, 열) — 그리는 쪽과 검사하는 쪽이 같은 순서를 본다.

    loop/line 축은 열이 'loop'|'outside'다. merge 축은 열이 'outer'|'price'|'merge'다
    (docs/superpowers/specs/2026-08-21-돈값-축-design.md)."""
    a = BY_ID.get(axis_id)
    if not a:
        return []
    if a.get('shape') == 'merge':
        out = [(c, n, g, 'outer') for c, n, g in a.get('outer', [])]
        out += [(c, n, g, 'price') for c, n, g in a.get('price', [])]
        mc, mn, mg = a['merge']
        out.append((mc, mn, mg, 'merge'))
        return out
    out = [(c, n, g, 'loop') for c, n, g in a['loop']]
    out += [(c, n, g, 'outside') for c, n, g in a['outside']]
    return out


def cell_of(axis_id, cell_id):
    for c, n, g, _col in cells(axis_id):
        if c == cell_id:
            return (n, g)
    return None


def all_cell_ids():
    out = set()
    for a in AXES:
        for c, _n, _g, _col in cells(a['id']):
            out.add((a['id'], c))
    return out


def shape_of(axis_id):
    """'loop'|'line'|'merge'. shape 키가 없으면 loop로 읽는다 — 기존 축 둘을 안 고치려고."""
    return (BY_ID.get(axis_id) or {}).get('shape', 'loop')


def edges_of(axis_id):
    """merge 축의 인과선 — [(출발 칸, 도착 칸, 부호, 근거 한 줄, 노트 파일, 줄 번호), …]."""
    return (BY_ID.get(axis_id) or {}).get('edges', [])


def flow_of(axis_id):
    """merge 축의 시간 흐름 정거장 — [(날짜, 라벨, 노트 파일), …]."""
    return (BY_ID.get(axis_id) or {}).get('flow', [])


