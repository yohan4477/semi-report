# -*- coding: utf-8 -*-
"""합류도 — 주제 하나가 어디로 모이는지.

섹션 타일은 카드를 주제별로 **나누는** 도구다. 여기는 반대로, 주제를 **가로질러**
카드 여럿이 한 곳으로 모인다는 것을 그림 한 장으로 보인다.
설계는 docs/superpowers/specs/2026-08-20-합류도-design.md.

읽는 층이다 — 카드 본문도 frontmatter도 안 고친다. 배정은 headline 문자열로만 가리키고,
그 headline이 실제 글에 없으면 생성이 멈춘다(gen_insightview의 assert, check_merge.py).

열은 셋으로 고정한다. 넷째 열을 열면 그림이 지도가 아니라 조직도가 된다.
merge 칸은 하나뿐이다 — 합류점이 둘이면 주제가 둘이라는 뜻이므로 dict를 나눈다.
"""

COLS = (('outer', '바깥에서 오는 것'),
        ('price', '값을 정하는 곳'),
        ('merge', '합류하는 곳'))

MERGES = [{
    'id': 'capital',
    'title': 'AI 자본조달 순환',
    'lede': '조달한 돈이 실제로 도는 컴퓨트가 됐는지를 GW·굿풋·토큰 단가로 되짚는다',
    # 바깥 칸은 회계사·미주사 코퍼스가 채우고, 합류 칸은 SemiAnalysis 코퍼스가 채운다.
    # 합류점을 「빅테크 잉여현금흐름」으로 잡으면 회계사 대시보드의 복제가 된다.
    'outer': [
        ('채권 · 리스 조달',
         ['빅테크는 쓴 돈만큼 장부에 담지 않는다']),
        # 보증 카드는 조달 칸에 뒀다가 옮겼다 — 본체가 엔비디아가 임대사 매출을 보증하고
        # 그 돈으로 자기 GPU가 팔리는 구조다. 조달 조건(10%→5.9%)은 그 결과지 주제가 아니다
        ('순환거래 · 백스톱',
         ['같은 보증 계약을 한쪽은 다리로, 한쪽은 부풀림으로 센다',
          '같은 날 메타는 코어위브의 고객이자 경쟁자가 됐다']),
        ('금리 · 조달비용',
         ['금리와 환율을 국내 수급으로 설명하는 방식이 깨졌다']),
    ],
    # 처음에 「배수의 기준선」 칸을 두고 성능 배수 카드를 넣었다. 그 카드의 2배·100배는
    # 밸류에이션 배수가 아니라 칩 성능 배수다 — 칸 이름을 보고 잘못 읽었다.
    # 값을 정하는 곳은 둘로 갈린다: 얼마를 남기나(마진), 같은 칩에서 얼마나 뽑나(단가).
    'price': [
        ('마진 — 누가 얼마를 남기나',
         ['앤트로픽은 흑자, 오픈AI는 매출만큼 적자',
          'AI 값은 내려가는데 파는 쪽 마진은 오른다']),
        ('컴퓨트 단가 — 같은 칩에서 얼마나',
         ['같은 칩을 두고 2배와 100배가 같이 나온다',
          '수혜 엔비디아·AMD, 위기 세레브라스·Groq: 소프트웨어가 1.9배']),
    ],
    'merge': ('컴퓨트 1단위가 버는 돈',
              ['같은 1GW인데 매출이 열 배 다르다',
               '사 오는 과제가 병목이라더니 산 GPU가 74% 놀았다']),
}]


def cells(m):
    """(칸 id, 열 id, 라벨, headline 목록) — 그리는 쪽과 검사하는 쪽이 같은 순서를 본다."""
    out = []
    for col, _title in COLS:
        rows = m[col] if col != 'merge' else [m[col]]
        for i, (label, heads) in enumerate(rows):
            out.append(('%s:%s:%d' % (m['id'], col, i), col, label, list(heads)))
    return out


def cell_index():
    """headline -> 그 글이 서는 칸 id 목록. 한 글이 여러 지도에 서는 것은 허용한다."""
    idx = {}
    for m in MERGES:
        for cid, _col, _label, heads in cells(m):
            for h in heads:
                idx.setdefault(h, []).append(cid)
    return idx
